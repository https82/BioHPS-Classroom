def render_cell_lesson(student):
    st.markdown('## 细胞学说是怎样建立的？')
    st.write('从观察软木开始，认识细胞学说的证据、核心内容和适用范围。')
    tabs=st.tabs(['系统讲解','科学史探究','知识检测'])
    with tabs[0]:
        idx=st.selectbox('本课学习内容',range(len(LESSON_STEPS)),format_func=lambda i:f'{i+1:02d} · {LESSON_STEPS[i][0]}',key=f'cell_step_{student}')
        st.progress((idx+1)/len(LESSON_STEPS))
        st.markdown('### '+LESSON_STEPS[idx][0])
        st.markdown(LESSON_STEPS[idx][1])
    with tabs[1]:
        st.markdown('### 从观察到细胞学说')
        for name,detail in [
            ('胡克的观察','软木切片呈现有规律的小室，打开微观观察的入口'),
            ('更多活细胞观察','其他研究者观察活细胞与微生物，增加不同样本的证据'),
            ('动植物研究的汇合','施莱登、施旺将不同生物的研究联系起来'),
            ('细胞来源观点的发展','后续研究逐渐完善关于新细胞来源的解释')]:
            st.markdown(f'**{name}：** {detail}')
        with st.form(f'cell_hps_{student}'):
            choice=st.radio('如果想检验“不同生物具有共同细胞结构基础”，哪种研究更可靠？',
                            ['只观察一次软木切片','比较多种动植物细胞的独立观察结果','不观察直接引用名人观点'],index=None)
            did=st.form_submit_button('查看我的判断')
        if did:
            if choice is None:st.warning('先选择一个方案。')
            else:
                correct=choice.startswith('比较')
                st.success('你的证据选择合理。') if correct else st.warning('单个切片和人物权威都不足以支持普遍结论。')
                st.write('比较多个生物类群和不同观察者的结果，能让理论归纳有更充分的证据。')
    with tabs[2]:
        idx=st.selectbox('练习题',range(len(CHECKS)),format_func=lambda i:f'第{i+1}题 · {CHECKS[i][0][:22]}',key=f'cell_quiz_{student}')
        stem,options,correct,why,tag=CHECKS[idx]
        st.markdown('### '+stem)
        with st.form(f'cell_quiz_form_{student}_{idx}'):
            answer=st.radio('选择你的答案',options,index=None)
            submit=st.form_submit_button('提交答案并记录')
        if submit:
            if answer is None:st.warning('请选择答案。')
            else:
                q={'id':f'V102-C{idx+1:02d}','card_id':'HS-001','grade':'高中',
                   'topic':'细胞学说','type':'基础与理解','question':stem,'options':options,
                   'answer':correct,'explanation':why,'error_tag':tag}
                result=add_attempt(student,q,options.index(answer))
                st.session_state[f'cell_quiz_feedback_{student}_{idx}']=result['correct']
        if f'cell_quiz_feedback_{student}_{idx}' in st.session_state:
            good=st.session_state[f'cell_quiz_feedback_{student}_{idx}']
            st.success('回答正确！') if good else st.warning('这道题还需要再想一想。')
            st.markdown('**解析：** '+why)
