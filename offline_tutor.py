"""Transparent, deterministic course-material fallback; never masquerades as an LLM."""
import re


def offline_explanation(question, groundings, history=None):
    if not groundings:
        return ('我暂时没有找到与你的问题直接对应的课程内容。你可以提供具体知识点，'
                '或者从“课程学习”选择章节，再来提问。')
    head=groundings[0]
    title=head.get('title','相关知识')
    texts=[]
    for src in groundings[:3]:
        raw=re.sub(r'\s+',' ',str(src.get('summary',''))).strip()
        if raw and raw not in texts:
            texts.append(raw[:370])
    base='\n\n'.join(texts[:2])
    # Follow-up hints are grounded in the retrieved course material, not model-generated reasoning.
    prior=next((m[1] for m in reversed(history or []) if m[0]=='user'),None)
    hint=(f'你之前问过“{prior[:60]}”，可以继续对照本节概念。' if prior and any(k in question for k in ('再','举例','那','为什么','听不懂')) else '')
    prompt=head.get('guide_question') or '你能试着用自己的话解释刚才的知识点吗？'
    return f'### {title}\n\n{base}\n\n{hint}\n\n**检查理解：** {prompt}\n\n如果你想进一步讨论实验与推理，可以在“跟着科学家探索”中操作。'


